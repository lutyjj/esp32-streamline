/**
 * Writes `src/generated/facts.ts`: what the device contract says about its
 * operations that the generated client does not carry, namely which writes
 * can restart the device and which reads need the admin key.
 */

import { readFileSync, writeFileSync } from 'node:fs';

interface Operation {
  security?: Record<string, string[]>[];
  'x-restarting'?: boolean;
}

const contract = JSON.parse(
  readFileSync(new URL('../../docs/openapi.json', import.meta.url), 'utf8'),
) as { paths: Record<string, { get?: Operation; post?: Operation }> };
const paths = Object.entries(contract.paths);

function list(name: string, doc: string, entries: string[]): string {
  const items = entries.map((path) => `  '${path}',\n`).join('');
  return `/** ${doc} */\nexport const ${name}: ReadonlySet<string> = new Set([\n${items}]);\n`;
}

writeFileSync(
  new URL('../src/generated/facts.ts', import.meta.url),
  [
    '// Generated by scripts/contractFacts.ts from docs/openapi.json. Do not edit.\n',
    list(
      'RESTARTING_WRITES',
      'Writes marked `x-restarting`: they can restart the device, which refuses them during an update.',
      paths.filter(([, operations]) => operations.post?.['x-restarting']).map(([path]) => path),
    ),
    list(
      'AUTHENTICATED_READS',
      'Reads that need the admin key; every other read is open.',
      paths.filter(([, operations]) => operations.get?.security?.length).map(([path]) => path),
    ),
  ].join('\n'),
);
