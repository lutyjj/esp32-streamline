/**
 * Writes what each contract says about its operations that the generated
 * client does not carry: `src/generated/facts.ts` for the device (which
 * writes can restart it, which reads need the admin key) and
 * `src/generated/bridgeFacts.ts` for the bridge (which reads need its token).
 */

import { readFileSync, writeFileSync } from 'node:fs';

interface Operation {
  security?: Record<string, string[]>[];
  'x-restarting'?: boolean;
}

type Paths = [string, Record<string, Operation | undefined>][];

function paths(contract: string): Paths {
  const document = JSON.parse(
    readFileSync(new URL(`../../docs/${contract}`, import.meta.url), 'utf8'),
  );
  return Object.entries(document.paths);
}

function list(name: string, doc: string, entries: string[]): string {
  const items = entries.map((path) => `  '${path}',\n`).join('');
  return `/** ${doc} */\nexport const ${name}: ReadonlySet<string> = new Set([\n${items}]);\n`;
}

function gatedReads(operations: Paths): string[] {
  return operations
    .filter(([, operation]) => operation.get?.security?.length)
    .map(([path]) => path);
}

function write(file: string, contract: string, parts: string[]): void {
  writeFileSync(
    new URL(`../src/generated/${file}`, import.meta.url),
    [
      `// Generated by scripts/contractFacts.ts from docs/${contract}. Do not edit.\n`,
      ...parts,
    ].join('\n'),
  );
}

const device = paths('openapi.json');
write('facts.ts', 'openapi.json', [
  list(
    'RESTARTING_WRITES',
    'Writes marked `x-restarting`: they can restart the device, which refuses them during an update.',
    device.filter(([, operations]) => operations.post?.['x-restarting']).map(([path]) => path),
  ),
  list(
    'AUTHENTICATED_READS',
    'Reads that need the admin key; every other read is open.',
    gatedReads(device),
  ),
]);

const bridge = paths('bridge-openapi.json');
// The bridge console sends its token with every write, which holds while the contract gates them all.
const openWrites = bridge.flatMap(([path, operations]) =>
  Object.entries(operations)
    .filter(([method, operation]) => method !== 'get' && !operation?.security?.length)
    .map(([method]) => `${method.toUpperCase()} ${path}`),
);
if (openWrites.length) throw new Error(`bridge writes without the token: ${openWrites.join(', ')}`);
write('bridgeFacts.ts', 'bridge-openapi.json', [
  list(
    'TOKEN_READS',
    'Reads that need the bridge API token; every other read is open, and every write needs it.',
    gatedReads(bridge),
  ),
]);
